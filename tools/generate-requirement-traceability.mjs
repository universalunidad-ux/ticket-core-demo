#!/usr/bin/env node
import { mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = join(root, "governance/points-first-requirements.json");
const DECISIONS = new Set([
  "PROMOTABLE_LOCAL",
  "HUMAN_ADJUDICATION_REQUIRED",
  "DUPLICATE_OR_DOUBLE_COUNT_RISK",
  "INTEGRATION_REQUIRED",
  "ALREADY_CREDITED_REFERENCE_ONLY",
  "HOSTED_OR_STAGING_REQUIRED"
]);

export function loadSource(path = sourcePath) {
  return JSON.parse(readFileSync(path, "utf8"));
}

export function validateSource(source) {
  const failures = [];
  if (source.schemaVersion !== 1) failures.push("SCHEMA_VERSION_INVALID");
  if (!/^[0-9a-f]{40}$/.test(source.base || "")) failures.push("BASE_INVALID");
  if (!(source.pointsBefore > 0) || !(source.totalWeight > 0)) failures.push("POINTS_INVALID");
  const ids = new Set();
  for (const row of source.rows || []) {
    if (!row.id || ids.has(row.id)) failures.push(`ROW_ID_DUPLICATE_OR_MISSING:${row.id || "EMPTY"}`);
    ids.add(row.id);
    for (const field of ["phase", "owner", "test", "evidence", "decision", "creditKey"]) {
      if (!row[field]) failures.push(`ROW_FIELD_MISSING:${row.id}:${field}`);
    }
    if (!DECISIONS.has(row.decision)) failures.push(`ROW_DECISION_INVALID:${row.id}`);
    if (!Number.isFinite(row.currentCredit) || !Number.isFinite(row.localCeiling)) failures.push(`ROW_CREDIT_INVALID:${row.id}`);
    if (row.localCeiling < row.currentCredit) failures.push(`ROW_CREDIT_REGRESSION:${row.id}`);
  }
  const byCredit = Map.groupBy(source.rows || [], (row) => row.creditKey);
  for (const [key, rows] of byCredit) {
    if (rows.length > 1 && rows.some((row) => row.decision === "PROMOTABLE_LOCAL")) {
      failures.push(`DOUBLE_CREDIT_PROMOTABLE:${key}`);
    }
  }
  return { ok: failures.length === 0, failures, byCredit };
}

export function buildArtifacts(source, head = source.base) {
  const validation = validateSource(source);
  if (!validation.ok) throw new Error(validation.failures.join(","));
  if (!/^[0-9a-f]{40}$/.test(head)) throw new Error("HEAD_INVALID");
  const rows = source.rows.map((row) => ({
    ...row,
    commit: head,
    proposedDelta: row.decision === "PROMOTABLE_LOCAL"
      ? Number((row.localCeiling - row.currentCredit).toFixed(4))
      : 0
  }));
  const duplicateGroups = [...validation.byCredit]
    .filter(([, grouped]) => grouped.length > 1)
    .map(([creditKey, grouped]) => ({ creditKey, rows: grouped.map((row) => row.id).sort(), disposition: "NO_AUTOMATIC_CREDIT" }));
  const netDelta = Number(rows.reduce((sum, row) => sum + row.proposedDelta, 0).toFixed(4));
  const proposedTotal = Number((source.pointsBefore + netDelta).toFixed(4));
  const traceability = {
    schemaVersion: 1,
    unit: source.unit,
    base: source.base,
    head,
    pointsBefore: source.pointsBefore,
    totalWeight: source.totalWeight,
    rowsEvaluated: rows.length,
    rowsPromotable: rows.filter((row) => row.proposedDelta > 0).length,
    netDelta,
    proposedTotal,
    proposedPercent: Number((proposedTotal / source.totalWeight * 100).toFixed(4)),
    rows
  };
  return { traceability, doubleCredit: { schemaVersion: 1, duplicateGroups } };
}

export function renderMarkdown(source, artifacts) {
  const lines = [
    "# Points-first requirement traceability",
    "",
    "> Generated by `tools/generate-requirement-traceability.mjs` from `governance/points-first-requirements.json`; do not edit manually.",
    "",
    `Unit: \`${source.unit}\``,
    `Base: \`${source.base}\``,
    `Generated commit input: \`${artifacts.traceability.head}\``,
    "",
    "| Requirement | Owner | Commit | Test owner | Evidence | Decision | Max local delta |",
    "|---|---|---|---|---|---|---:|"
  ];
  for (const row of artifacts.traceability.rows) {
    lines.push(`| ${row.id} | ${row.owner} | \`${row.commit.slice(0, 12)}\` | \`${row.test}\` | \`${row.evidence}\` | ${row.decision} | ${row.proposedDelta.toFixed(2)} |`);
  }
  lines.push("", `Net maximum supported by the source contract: **+${artifacts.traceability.netDelta.toFixed(2)}**.`);
  lines.push("Rows needing human, hosted, integration, or prior-credit adjudication remain at zero delta.");
  return `${lines.join("\n")}\n`;
}

function parseArgs(argv) {
  const args = { outDir: join(root, "docs/generated"), head: null };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--out-dir") args.outDir = resolve(argv[++i]);
    else if (argv[i] === "--head") args.head = argv[++i];
    else throw new Error(`ARGUMENT_INVALID:${argv[i]}`);
  }
  return args;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const source = loadSource();
  const artifacts = buildArtifacts(source, args.head || source.base);
  mkdirSync(args.outDir, { recursive: true });
  writeFileSync(join(args.outDir, "requirement-traceability.json"), `${JSON.stringify(artifacts.traceability, null, 2)}\n`);
  writeFileSync(join(args.outDir, "double-credit.json"), `${JSON.stringify(artifacts.doubleCredit, null, 2)}\n`);
  writeFileSync(join(args.outDir, "POINTS_FIRST_REQUIREMENT_TRACEABILITY.md"), renderMarkdown(source, artifacts));
  console.log(`TRACEABILITY_ROWS=${artifacts.traceability.rowsEvaluated}`);
  console.log(`PROMOTABLE_ROWS=${artifacts.traceability.rowsPromotable}`);
  console.log(`NET_LOCAL_DELTA=${artifacts.traceability.netDelta.toFixed(2)}`);
  console.log("DOUBLE_CREDIT_GATE=PASS");
  console.log("TRACEABILITY_GENERATION=PASS");
}

if (process.argv[1] && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href) main();
